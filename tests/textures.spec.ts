test('duplicate existing texture import requires explicit classification; failed and stale saves retain drafts', async ({ page, request }) => {
  const buffer = await picture();
  const { image } = await (await post(request, 'images', { action: 'save', filename: 'Existing.png', bytes: buffer.toString('base64') })).json();
  await failStorage(page, 'images', 'save');
  await page.goto('/textures');
  await page.getByLabel('Choose image').setInputFiles({ name: 'Texture.png', mimeType: 'image/png', buffer });
  await expect(page.getByRole('alert').first()).toContainText('could not be imported');
  await page.evaluate(() => sessionStorage.setItem('allowSave', '1'));
  await page.getByLabel('Choose image').setInputFiles({ name: 'Texture.png', mimeType: 'image/png', buffer });
  await expect(page.getByRole('status').first()).toContainText('already saved');
  expect((await records(request))[0]).toEqual(image);
  await page.getByRole('button', { name: 'Review saved image' }).click();
  await page.getByLabel('Use as texture').check();
  await page.evaluate(() => sessionStorage.removeItem('allowSave'));
  await page.getByRole('button', { name: 'Save image details' }).click();
  await expect(page.getByRole('alert').first()).toContainText('Details could not be saved');
  await expect(page.getByLabel('Use as texture')).toBeChecked();
  await page.evaluate(() => sessionStorage.setItem('allowSave', '1'));
  await post(request, 'images', { action: 'update', id: image.id, expectedRevision: image.revision, fields: { ...fields(image), title: 'Changed elsewhere' } });
  await page.getByRole('button', { name: 'Save image details' }).click();
  await expect(page.getByRole('alert').first()).toContainText('changed in another tab');
  await expect(page.getByLabel('Use as texture')).toBeChecked();
  page.once('dialog', dialog => dialog.dismiss()); await page.getByRole('button', { name: 'Reload textures' }).click();
  await expect(page.getByLabel('Image title')).toHaveValue('Existing.png');
  page.once('dialog', dialog => dialog.accept()); await page.getByRole('button', { name: 'Reload textures' }).click();
  await expect(page.getByLabel('Image title')).toHaveValue('Changed elsewhere');
  await expect(page.getByLabel('Use as texture')).not.toBeChecked();
  await page.getByLabel('Use as texture').check();
  await page.getByRole('button', { name: 'Save image details' }).click();
  await expect(page.getByText('1 of 1 textures')).toBeVisible();
});

test('texture membership rejects a stale collection and reload appends without losing its order or tags', async ({ page, request }) => {
  const { image, pdf } = await seed(request);
  const collection = await (await post(request, 'collections', { action: 'save', id: randomUUID(), expectedRevision: null, name: 'Materials', members: [{ kind: 'notes', id: note.id }], tags: ['Design'] })).json();
  await page.goto(`/textures?image=${image.id}`);
  await page.getByRole('combobox', { name: 'Choose collection', exact: true }).selectOption(collection.id);
  const changed = await (await post(request, 'collections', { action: 'save', id: collection.id, expectedRevision: collection.revision, name: 'Materials', members: [{ kind: 'pdfs', id: pdf.id }, ...collection.members], tags: ['Paper'] })).json();
  await page.getByRole('button', { name: 'Add image to collection' }).click();
  await expect(page.getByRole('alert').first()).toContainText('changed or was deleted');
  expect((await (await request.get('/api/library?kind=collections')).json()).collections[0]).toEqual(changed);
  await page.getByRole('button', { name: 'Reload textures' }).click();
  await page.getByRole('combobox', { name: 'Choose collection', exact: true }).selectOption(collection.id);
  await page.getByRole('button', { name: 'Add image to collection' }).click();
  await expect(page.getByRole('status').first()).toContainText('Added to “Materials”');
  const saved = (await (await request.get('/api/library?kind=collections')).json()).collections[0];
  expect(saved.members).toEqual([...changed.members, { kind: 'images', id: image.id }]); expect(saved.tags).toEqual(changed.tags);
  await expect(page.getByRole('button', { name: 'Add image to collection' })).toBeDisabled();
});
