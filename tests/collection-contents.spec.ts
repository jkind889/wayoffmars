import { test, expect } from './fixtures';
import { post, seed, note } from './helpers/tags';
import { randomUUID, createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import sharp from 'sharp';
import type { APIRequestContext } from '@playwright/test';

async function font(request: APIRequestContext) {
  const bytes = readFileSync('tests/fixtures/fonts/SourceSerif4-Regular.ttf'), id = createHash('sha256').update(bytes).digest('hex');
  expect((await post(request, 'fonts', { action: 'save', font: { id, name: 'SourceSerif4-Regular.ttf', size: bytes.length, bytes: bytes.toString('base64'), addedAt: 1 } })).ok()).toBe(true);
  return { kind: 'fonts' as const, id };
}

