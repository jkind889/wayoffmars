test('font assets wait until their card nears view and are released when the collection closes', async ({ page, request }) => {
  const members: { kind: 'notes' | 'fonts'; id: string }[] = [];
  for (let index = 0; index < 20; index++) {
    const id = `bounded-${index}`;
    await post(request, 'notes', { action: 'write', id, expectedRevision: null, note: { ...note, id, title: `Note ${index}`, body: 'Bounded preview text. '.repeat(1000) } });
    members.push({ kind: 'notes', id });
  }
  const savedFont = await font(request); members.push(savedFont);
  const collection = await (await post(request, 'collections', { action: 'save', id: randomUUID(), expectedRevision: null, name: 'Long board', members })).json();
  const assets: string[] = []; page.on('request', request => { if (request.url().includes('kind=asset&')) assets.push(request.url()); });
  await page.goto(`/collections?collection=${collection.id}`);
  await expect(page.getByRole('heading', { name: 'Long board', exact: true })).toBeFocused();
  await expect(page.locator('.collection-items-grid article')).toHaveCount(21);
  await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))));
  expect(assets).toEqual([]);
  expect(await page.locator('.collection-items-grid .note-body').evaluateAll(elements => elements.every(element => element.textContent!.length <= 400))).toBe(true);
  await page.getByRole('article', { name: 'SourceSerif4-Regular.ttf' }).scrollIntoViewIfNeeded();
  await expect(page.locator('.collection-items-grid .font-sample')).toBeVisible();
  expect(assets).toHaveLength(1);
  expect(await page.evaluate(id => Array.from(document.fonts).some(face => face.family === `collection-${id}`), savedFont.id)).toBe(true);
  await page.getByRole('button', { name: 'Close collection', exact: true }).click();
  expect(await page.evaluate(id => Array.from(document.fonts).some(face => face.family === `collection-${id}`), savedFont.id)).toBe(false);
});
