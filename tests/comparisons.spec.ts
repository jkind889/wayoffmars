import { test, expect } from './fixtures';
import { post } from './helpers/tags';
import sharp from 'sharp';
import path from 'node:path';

test('image shortlist survives filtering, limits to four and handles deletion with keyboard/mobile comparison', async ({ page, request }) => {
  const images = [];
  for (let i = 0; i < 5; i++) {
    const bytes = await sharp({ create: { width: 40 + i, height: 30, channels: 3, background: '#888' } }).png().toBuffer();
    images.push((await (await post(request, 'images', { action: 'save', filename: `Image${i}.png`, bytes: bytes.toString('base64') })).json()).image);
  }
  await page.goto('/images');
  for (let i = 0; i < 4; i++) await page.getByRole('button', { name: `Compare Image${i}.png` }).click();
  await expect(page.getByRole('button', { name: 'Compare Image4.png' })).toBeDisabled();
  await page.getByLabel('Filter images').fill('Image4');
  await expect(page.getByText('4 of 4 images shortlisted.', { exact: false })).toBeVisible();
  await post(request, 'images', { action: 'delete', id: images[0].id, expectedRevision: images[0].revision });
  const trigger = page.getByRole('button', { name: 'Compare images', exact: true });
  await trigger.click();
  const dialog = page.getByRole('dialog', { name: 'Compare images' });
  await expect(dialog.getByText('Image no longer available')).toBeVisible();
  await expect(dialog.getByRole('img')).toHaveCount(3);
  await expect.poll(() => dialog.getByRole('img').evaluateAll(images => images.every(image => (image as HTMLImageElement).naturalWidth > 0))).toBe(true);
  await page.screenshot({ path: '/tmp/wayoffmars-compare-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: '/tmp/wayoffmars-compare-mobile.png' });
  await page.keyboard.press('Escape');
  await expect(dialog).not.toBeVisible();
  await expect(trigger).toBeFocused();
});

test('font comparisons use shared specimen appearance and detect deleted saved fonts', async ({ page, request }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto('/');
  await expect(page).toHaveTitle('Font library | wayoffmars');
  await expect(page.getByRole('heading', { name: 'Your font library' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Choose font files' })).toBeEnabled();
  await page.getByLabel('Choose font files').setInputFiles(['ttf', 'woff'].map(ext => path.join(__dirname, `fixtures/fonts/SourceSerif4-Regular.${ext}`)));
  await expect(page.locator('.font-row')).toHaveCount(2);
  for (const ext of ['ttf', 'woff']) await page.getByRole('button', { name: `Compare SourceSerif4-Regular.${ext}` }).click();
  await page.getByLabel('Filter saved fonts').fill('nothing');
  const trigger = page.getByRole('button', { name: 'Font comparison (2/4)', exact: true });
  await trigger.click();
  const panel = page.getByRole('complementary', { name: 'Font comparison' });
  await expect(panel.getByRole('heading')).toBeFocused();
  await expect(trigger).toHaveAttribute('aria-expanded', 'true');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Compare fonts', exact: true }).click();
  await panel.getByText('Comparison settings', { exact: true }).click();
  await panel.getByLabel('Comparison text').fill('A shared specimen');
  await panel.getByLabel('Tracking (em)').fill('0.2');
  await panel.getByLabel('Alignment', { exact: true }).selectOption('center');
  await expect(panel.locator('.font-sample')).toHaveCount(2);
  await expect(panel.locator('.font-sample').first()).toHaveCSS('text-align', 'center');
  // Library controls and selection remain usable beside the open panel.
  await page.getByLabel('Filter saved fonts').fill('');
  await expect(page.locator('.font-row')).toHaveCount(2);
  await page.getByRole('textbox', { name: 'Preview text', exact: true }).fill('Live shared specimen');
  await expect(panel.locator('.font-sample').first()).toHaveText('Live shared specimen');
  await page.getByRole('button', { name: 'Compare SourceSerif4-Regular.woff', exact: true }).click();
  await expect(panel.locator('.font-sample')).toHaveCount(1);
  await page.getByRole('button', { name: 'Compare SourceSerif4-Regular.woff', exact: true }).click();
  await expect(panel.locator('.font-sample')).toHaveCount(2);
  const cdp = await page.context().newCDPSession(page);
  await cdp.send('DOM.enable'); await cdp.send('CSS.enable');
  const { root } = await cdp.send('DOM.getDocument');
  const { nodeId } = await cdp.send('DOM.querySelector', { nodeId: root.nodeId, selector: '.font-comparison-panel .font-sample' });
  const rendered = await cdp.send('CSS.getPlatformFontsForNode', { nodeId });
  expect(rendered.fonts.some(font => font.isCustomFont && font.glyphCount > 0)).toBe(true);
  await cdp.detach();
  await panel.getByText('Comparison settings', { exact: true }).click();
  await page.getByLabel('Filter saved fonts').scrollIntoViewIfNeeded();
  const resultsBox = await page.locator('.font-results').boundingBox();
  const panelBox = await panel.boundingBox();
  expect(resultsBox!.x + resultsBox!.width).toBeLessThan(panelBox!.x);
  await page.screenshot({ path: '/tmp/wayoffmars-font-compare-desktop.png' });
  for (const width of [1440, 1024, 820, 768]) {
    await page.setViewportSize({ width, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect(await panel.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  }
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await panel.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await panel.getByRole('heading', { name: 'Font comparison', exact: true }).focus();
  await page.screenshot({ path: '/tmp/wayoffmars-font-compare-mobile.png' });
  await page.keyboard.press('Escape');
  await expect(panel).not.toBeVisible();
  await expect(trigger).toBeFocused();
  await expect(page.getByRole('textbox', { name: 'Preview text', exact: true })).toHaveValue('Live shared specimen');
  const fonts = await (await request.get('/api/library?kind=fonts')).json();
  await post(request, 'fonts', { action: 'delete', id: fonts[0].id });
  await trigger.click();
  await page.getByRole('button', { name: 'Compare fonts', exact: true }).click();
  await expect(panel.getByText('Font no longer available')).toBeVisible();
  await panel.getByText('Comparison settings', { exact: true }).click();
  await expect(panel.getByLabel('Tracking (em)')).toHaveValue('0.2');
  await expect(panel.getByLabel('Alignment', { exact: true })).toHaveValue('center');
  expect(errors).toEqual([]);
});

test('font panel opens empty, preserves selection on close, and supports keyboard navigation and clear', async ({ page }) => {
  await page.goto('/');
  const trigger = page.getByRole('button', { name: /^Font comparison \(/ });
  const panel = page.getByRole('complementary', { name: 'Font comparison' });
  await expect(page.getByRole('button', { name: 'Clear shortlist' })).not.toBeVisible();
  await trigger.focus();
  await page.keyboard.press('Enter');
  await expect(panel.getByRole('heading')).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(panel.getByRole('button', { name: 'Close comparison' })).toBeFocused();
  await expect(panel.getByRole('button', { name: 'Compare fonts', exact: true })).toBeDisabled();
  await expect(panel.getByRole('button', { name: 'Clear shortlist' })).toBeDisabled();
  // Empty panel has no focus trap: Tab reaches the library filter.
  await page.keyboard.press('Tab');
  await expect(page.getByLabel('Filter saved fonts')).toBeFocused();
  await expect(page.getByRole('button', { name: 'Choose font files' })).toBeEnabled();
  await page.getByLabel('Choose font files').setInputFiles(['ttf', 'woff', 'woff2', 'otf'].map(ext => path.join(__dirname, `fixtures/fonts/SourceSerif4-Regular.${ext}`)));
  await expect(page.locator('.font-row')).toHaveCount(4);
  for (const ext of ['ttf', 'woff', 'woff2', 'otf']) await page.getByRole('button', { name: `Compare SourceSerif4-Regular.${ext}`, exact: true }).click();
  await expect(panel.getByText('4 of 4 fonts shortlisted.', { exact: false })).toBeVisible();
  await panel.getByRole('button', { name: 'Compare fonts', exact: true }).click();
  await expect(panel.locator('.comparison-card')).toHaveCount(4);
  await panel.getByRole('button', { name: 'Close comparison' }).click();
  await expect(trigger).toBeFocused();
  await expect(trigger).toHaveAttribute('aria-expanded', 'false');
  await trigger.click();
  await expect(panel.locator('.comparison-card')).toHaveCount(4);
  await panel.getByRole('button', { name: 'Remove from comparison' }).first().click();
  await expect(panel.getByRole('button', { name: 'Remove from comparison' }).first()).toBeFocused();
  await expect(trigger).toHaveText('Font comparison (3/4)');
  await panel.getByRole('button', { name: 'Clear shortlist' }).click();
  await expect(panel.getByRole('button', { name: 'Close comparison' })).toBeFocused();
  await expect(panel.locator('.comparison-card')).toHaveCount(0);
  await expect(trigger).toHaveText('Font comparison (0/4)');
  await expect(page.getByRole('button', { name: 'Compare SourceSerif4-Regular.ttf' })).toHaveAttribute('aria-pressed', 'false');
  await page.keyboard.press('Escape');
  await expect(trigger).toBeFocused();
  await page.setViewportSize({ width: 390, height: 844 });
  await trigger.click();
  await expect(panel.getByRole('heading')).toBeInViewport();
  await panel.getByRole('button', { name: 'Close comparison' }).click();
  await expect(trigger).toBeFocused();
  await page.getByLabel('Filter saved fonts').fill('woff2');
  await expect(page.locator('.font-row')).toHaveCount(1);
});

test('font comparison read failures can be retried without blocking the library', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Choose font files' })).toBeEnabled();
  await page.getByLabel('Choose font files').setInputFiles(['ttf', 'woff'].map(ext => path.join(__dirname, `fixtures/fonts/SourceSerif4-Regular.${ext}`)));
  await expect(page.locator('.font-row')).toHaveCount(2);
  for (const ext of ['ttf', 'woff']) await page.getByRole('button', { name: `Compare SourceSerif4-Regular.${ext}` }).click();
  await page.getByRole('button', { name: /^Font comparison \(/ }).click();
  const panel = page.getByRole('complementary', { name: 'Font comparison' });
  await page.route('**/api/library?kind=fonts', route => route.fulfill({ status: 503, json: { error: 'Temporary read failure' } }));
  await panel.getByRole('button', { name: 'Compare fonts', exact: true }).click();
  await expect(panel.getByRole('alert')).toContainText('Temporary read failure');
  await page.getByLabel('Filter saved fonts').fill('woff');
  await expect(page.locator('.font-row')).toHaveCount(1);
  await page.unroute('**/api/library?kind=fonts');
  let release!: () => void;
  const delayedRead = new Promise<void>(resolve => { release = resolve; });
  await page.route('**/api/library?kind=fonts', async route => { await delayedRead; await route.continue(); });
  const response = page.waitForResponse(response => response.url().endsWith('/api/library?kind=fonts'));
  await panel.getByRole('button', { name: 'Compare fonts', exact: true }).click();
  await expect(panel.getByRole('button', { name: 'Loading comparison…' })).toBeDisabled();
  await panel.getByRole('button', { name: 'Close comparison' }).click();
  await page.getByLabel('Filter saved fonts').fill('ttf');
  release();
  await response;
  await expect(panel).not.toBeVisible();
  await expect(page.getByLabel('Filter saved fonts')).toBeFocused();
  await page.getByRole('button', { name: /^Font comparison \(/ }).click();
  await expect(panel.locator('.font-sample')).toHaveCount(2);
  await expect(panel.getByRole('alert')).toHaveCount(0);
});
